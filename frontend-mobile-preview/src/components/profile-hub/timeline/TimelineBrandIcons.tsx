export function renderBrandPlatformIcon(platform?: TimelinePlatform | TimelineSource, size = 15): React.ReactNode {
  switch (platform) {
    case 'all':
      return <AllSourcesBrandIcon size={size} />;
    case 'x':
      return <XBrandIcon size={size} />;
    case 'youtube':
      return <YouTubeBrandIcon size={size + 1} />;
    case 'pinterest':
      return <PinterestBrandIcon size={size} />;
    case 'imgur':
      return <ImgurBrandIcon size={size} />;
    default: {
      const iconKind = getDynamicSourceIconKind(platform);
      if (iconKind === 'video_portal') return <VideoPortalBrandIcon size={size} />;
      if (iconKind === 'gallery_hd') return <GalleryHdCatalogIcon size={size} />;
      if (iconKind === 'forum_board') return <ForumBoardIcon size={size} />;
      if (iconKind === 'gallery_catalog') return <GalleryCatalogIcon size={size} />;
      return <StudioPlayBrandIcon size={size} />;
    }
  }
}
